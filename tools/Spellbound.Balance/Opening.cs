using System.Globalization;
using System.Text;
using Spellbound.Domain;

namespace Spellbound.Balance;

/// <summary>
/// The opening study (the research's "replay days 1–7 thousands of times"): many short runs of one mixed server,
/// each with its own seed and check-in times jittered by up to an hour, so the luck of who plays first and how battles
/// roll averages out. Reports each strategy's spread at the end, and how far the leader pulls ahead of the median.
/// </summary>
public sealed class Opening(GameRules rules, DateTimeOffset start)
{
    /// <summary>The strategies in every run, and the hours each checks in (before jitter).</summary>
    private static IEnumerable<(Func<Bot> Bot, int[] Hours)> Lineup()
    {
        int[] thriceDaily = [8, 13, 21];
        int[] daily = [20];
        return
        [
            (() => new Builder("Builder"), thriceDaily),
            (() => new Builder("Builder, 40% nodes", nodeShare: 0.4), thriceDaily),
            (() => new Builder("Builder, once a day"), daily),
            (() => new ExploreFirst("Explore first", untilDay: 3), thriceDaily),
            (() => new Turtle("Turtle"), thriceDaily),
            (() => new Warmonger("Warmonger"), thriceDaily),
        ];
    }

    public string Run(int runs, int days, int firstSeed)
    {
        var results = new List<(int Run, string Player, Mage Mage, int TurnsLost, int AttacksMade, int AttacksTaken)>();
        for (var run = 0; run < runs; run++)
        {
            var seed = firstSeed + run;
            var jitter = new SeededRandom(seed * 7919);
            var seats = Lineup().Select(l => new Seat(l.Bot(), [.. l.Hours.Select(h => Math.Clamp(h + (int)Math.Floor(jitter.NextDouble() * 3) - 1, 0, 23))]));
            var sim = new Sim($"run {run}", rules, seed, start, seats).Run(days);
            foreach (var (seat, mage) in sim.Players)
            {
                results.Add((run, seat.Bot.Name, mage, sim.TurnsLost(mage),
                    sim.Attacks.Count(a => a.Attacker == seat.Bot.Name), sim.Attacks.Count(a => a.Target == seat.Bot.Name)));
            }
        }

        var md = new StringBuilder();
        md.AppendLine("# Opening baseline");
        md.AppendLine();
        md.AppendLine(CultureInfo.InvariantCulture,
            $"Generated by `tools/Spellbound.Balance -- --opening {runs}` with the default `GameRules`; don't edit by hand. {runs} runs of days 1–{days} on one mixed server (seeds {firstSeed}–{firstSeed + runs - 1}), check-in times jittered by up to an hour per run. Each Mageborn step reruns this and compares against it; see [balance.md](balance.md) for the bots.");
        md.AppendLine();
        md.AppendLine(CultureInfo.InvariantCulture, $"## Each strategy on day {days}");
        md.AppendLine();
        md.AppendLine("Median, with the 10th–90th percentile range in brackets.");
        md.AppendLine();
        md.AppendLine("| Strategy | Land | Networth | Units | Turns lost at the cap | Attacks made | Attacks taken |");
        md.AppendLine("|---|---:|---:|---:|---:|---:|---:|");
        foreach (var group in results.GroupBy(r => r.Player))
        {
            md.AppendLine(string.Join(" | ",
                "| " + group.Key,
                Spread(group.Select(r => r.Mage.Land)),
                Spread(group.Select(r => r.Mage.Networth(rules))),
                Spread(group.Select(r => r.Mage.TotalUnits)),
                Spread(group.Select(r => r.TurnsLost)),
                Spread(group.Select(r => r.AttacksMade)),
                Spread(group.Select(r => r.AttacksTaken))) + " |");
        }

        // The research's measure of a runaway leader: rank 1's net worth against the server's median.
        var leads = results.GroupBy(r => r.Run).Select(run =>
        {
            var worths = run.Select(r => r.Mage.Networth(rules)).Order().ToList();
            return (double)worths[^1] / Median(worths);
        }).ToList();
        var winners = results.GroupBy(r => r.Run)
            .Select(run => run.MaxBy(r => r.Mage.Networth(rules)).Player)
            .GroupBy(p => p).OrderByDescending(g => g.Count());

        md.AppendLine();
        md.AppendLine("## The leader");
        md.AppendLine();
        md.AppendLine(CultureInfo.InvariantCulture,
            $"Rank 1's networth against the median player's: median {Percentile(leads, 0.5):F2}×, 10th–90th percentile {Percentile(leads, 0.1):F2}×–{Percentile(leads, 0.9):F2}×.");
        md.AppendLine();
        md.AppendLine("Who leads on the last day:");
        md.AppendLine();
        foreach (var winner in winners)
        {
            md.AppendLine(CultureInfo.InvariantCulture, $"- {winner.Key}: {winner.Count() * 100 / runs}% of runs");
        }

        return md.ToString();
    }

    private static string Spread(IEnumerable<int> values)
    {
        var list = values.Select(v => (double)v).ToList();
        return $"{N(Median(list))} ({N(Percentile(list, 0.1))}–{N(Percentile(list, 0.9))})";
    }

    private static double Median(IEnumerable<int> values) => Median(values.Select(v => (double)v).ToList());

    private static double Median(List<double> values) => Percentile(values, 0.5);

    private static double Percentile(List<double> values, double share)
    {
        var sorted = values.Order().ToList();
        return sorted[(int)Math.Round(share * (sorted.Count - 1))];
    }

    private static string N(double value) => value.ToString("N0", CultureInfo.InvariantCulture);
}
