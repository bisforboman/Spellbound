// Balance simulation: bots play Spellbound's real rules (Spellbound.Domain) for a round, and the results go to a
// markdown report. Deterministic: the same seed gives the same report. See docs/balance.md.
//
//   dotnet run --project tools/Spellbound.Balance -- [--days 28] [--seed 7] [--out docs/balance-results.md]
using System.Globalization;
using Spellbound.Balance;
using Spellbound.Domain;

var days = Arg("--days", 28);
var seed = Arg("--seed", 7);
var output = ArgText("--out", null) ?? "docs/balance-results.md";
var rules = GameRules.Default;
var start = new DateTimeOffset(2026, 1, 1, 0, 0, 0, TimeSpan.Zero);
int[] thriceDaily = [8, 13, 21];
int[] daily = [20];
int[] snapshots = [.. new[] { 1, 3, 7, 14, 21, 28 }.Where(d => d <= days)];

var scenarios = new[]
{
    new Sim("Peaceful server: economy only", rules, seed, start,
    [
        new Seat(new Builder("Builder-3x"), thriceDaily),
        new Seat(new Builder("Builder-1x"), daily),
        new Seat(new Turtle("Turtle-3x"), thriceDaily),
    ]),
    new Sim("Mixed server: builders, a turtle, warmongers and an idle account", rules, seed, start,
    [
        new Seat(new Builder("Builder-3x"), thriceDaily),
        new Seat(new Builder("Builder-1x"), daily),
        new Seat(new Turtle("Turtle-3x"), thriceDaily),
        new Seat(new Warmonger("Warmonger-3x"), thriceDaily),
        new Seat(new Warmonger("Warmonger-1x"), daily),
        new Seat(new Idle("Idle"), []),
    ]),
};

using var report = new StreamWriter(output);
report.WriteLine("# Balance simulation results");
report.WriteLine();
report.WriteLine("Generated by `tools/Spellbound.Balance` with the default `GameRules`; don't edit by hand. "
                 + $"{days} days, seed {seed}. Findings and proposals are in [balance.md](balance.md).");
report.WriteLine();
foreach (var sim in scenarios)
{
    report.Write(sim.Run(days).Report(snapshots));
}

Console.WriteLine($"Wrote {output}");

int Arg(string name, int fallback) =>
    ArgText(name, null) is { } text ? int.Parse(text, CultureInfo.InvariantCulture) : fallback;

string? ArgText(string name, string? fallback)
{
    var i = Array.IndexOf(args, name);
    return i >= 0 && i + 1 < args.Length ? args[i + 1] : fallback;
}
