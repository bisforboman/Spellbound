// Skirmish simulation: bots with different strategies play many seeded 4-seat games on the real rules
// (Spellbound.Domain.Skirmish), and the results go to a markdown report. It measures what the design promises: more than
// one way to win, games that stay open (an early leader doesn't always win), and luck that matters without deciding
// everything. Deterministic: the same seed gives the same report. See docs/skirmish-design.md.
//
//   dotnet run --project tools/Spellbound.SkirmishSim -- [--games 1000] [--seed 7] [--out docs/skirmish-sim-results.md]
using System.Globalization;
using System.Text;
using Spellbound.Domain;
using Spellbound.Domain.Skirmish;
using Spellbound.SkirmishSim;

var games = Arg("--games", 1000);
var seed = Arg("--seed", 7);
var output = ArgText("--out") ?? "docs/skirmish-sim-results.md";
var rules = SkirmishRules.Default;

Bot[] bots = [new Expander(), new Builder(), new Fighter(), new HalfPresent()];
var results = new List<GameResult>();
for (var g = 0; g < games; g++)
{
    // Rotate the seats so no bot always sits in the same place on the board.
    var seated = Enumerable.Range(0, bots.Length).Select(i => bots[(i + g) % bots.Length]).ToList();
    results.Add(Play(seated, rules, seed + g));
}

var text = new StringBuilder();
text.AppendLine("# Skirmish simulation results").AppendLine();
text.AppendLine("Generated by `tools/Spellbound.SkirmishSim` with the default `SkirmishRules`; don't edit by hand. "
                + $"{games} games of {bots.Length} seats, seeds {seed}–{seed + games - 1}, seats rotated every game. "
                + "Part A rules: claims, builds, recruits and the discovery deck; no attacks, hexes or spells yet, so mana and "
                + "armies only matter for contested claims.").AppendLine();

text.AppendLine("## Bots").AppendLine();
foreach (var bot in bots)
{
    text.AppendLine($"- **{bot.Name}:** {bot.Strategy}");
}

text.AppendLine().AppendLine("## Who wins").AppendLine();
text.AppendLine("| Bot | Wins | Win rate | Average points | Average regions | Average buildings |").AppendLine("|---|---|---|---|---|---|");
foreach (var bot in bots)
{
    var seats = results.SelectMany(r => r.Seats).Where(s => s.Bot == bot.Name).ToList();
    var wins = results.Count(r => r.Winner == bot.Name);
    text.AppendLine($"| {bot.Name} | {wins} | {Pct(wins, games)} | {seats.Average(s => s.Points):0.0} | {seats.Average(s => s.Regions):0.0} | {seats.Average(s => s.Buildings):0.0} |");
}

var earlyLeaderWins = results.Count(r => r.LeaderAfter6 == r.Winner);
var cardsDecided = results.Count(r => r.WinnerCardPoints > r.Margin);
var contests = results.Average(r => r.Contests);
text.AppendLine().AppendLine("## Is the game open?").AppendLine();
text.AppendLine($"- **The leader after round 6 wins** {Pct(earlyLeaderWins, games)} of games (lower means comebacks happen).");
text.AppendLine($"- **Winning margin:** median {Median(results.Select(r => r.Margin))} points over second place; "
                + $"{Pct(results.Count(r => r.Margin <= 3), games)} of games are won by 3 points or less.");
text.AppendLine($"- **Cards decided the game** in {Pct(cardsDecided, games)} of games (the winner's card points were more than their margin).");
text.AppendLine($"- **Contested claims:** {contests:0.0} a game on average.");
text.AppendLine($"- **How games end:** {Pct(results.Count(r => r.EndedEarly), games)} early, by holding half the board; the rest after {rules.Rounds} rounds "
                + $"(average {results.Average(r => r.Rounds):0.0} rounds).");
text.AppendLine($"- **Seat order:** seat 1 wins {Pct(results.Count(r => r.WinnerSeat == 0), games)}, seat 2 {Pct(results.Count(r => r.WinnerSeat == 1), games)}, "
                + $"seat 3 {Pct(results.Count(r => r.WinnerSeat == 2), games)}, seat 4 {Pct(results.Count(r => r.WinnerSeat == 3), games)}.");

text.AppendLine().AppendLine("## Resources at the end").AppendLine();
text.AppendLine("| Bot | Gold | Mana | Units |").AppendLine("|---|---|---|---|");
foreach (var bot in bots)
{
    var seats = results.SelectMany(r => r.Seats).Where(s => s.Bot == bot.Name).ToList();
    text.AppendLine($"| {bot.Name} | {seats.Average(s => s.Gold):N0} | {seats.Average(s => s.Mana):N0} | {seats.Average(s => s.Units):0} |");
}

text.AppendLine().AppendLine("Mana piles up because part A has no spells: part B (casts and hexes) is where it gets spent, "
                             + "and its costs are set from these numbers.");

File.WriteAllText(output, text.ToString());
Console.WriteLine(text);
Console.WriteLine($"Wrote {output}");
return;

static GameResult Play(List<Bot> seated, SkirmishRules rules, int seed)
{
    var game = SkirmishGame.Start([.. seated.Select((b, i) => ($"{b.Name}-{i + 1}", (MagicSchool)(i % 5)))], rules, new SeededRandom(seed));
    var luck = new SeededRandom(seed * 31 + 1);
    var choices = new Random(seed * 17 + 3);
    string? leaderAfter6 = null;
    var contests = 0;
    while (!game.Ended)
    {
        var orders = game.Seats.ToDictionary(s => s.Index, s => (IReadOnlyList<SkirmishOrder>)seated[s.Index].Orders(game, s.Index, choices));
        var report = game.PlayRound(orders, luck);
        contests += report.Public.Count(l => l.Contains(" was claimed by ", StringComparison.Ordinal));
        if (game.Round == 6)
        {
            leaderAfter6 = seated[game.Standings()[0].Index].Name;
        }
    }

    var standings = game.Standings();
    var winner = standings[0].Index;
    return new GameResult(
        seated[winner].Name,
        winner,
        leaderAfter6 ?? seated[winner].Name,
        game.Score(winner).Total - game.Score(standings[1].Index).Total,
        game.Score(winner).Cards,
        contests,
        game.Round,
        game.Round < rules.Rounds,
        [.. game.Seats.Select(s => new SeatResult(
            seated[s.Index].Name, game.Score(s.Index).Total, game.RegionsOf(s.Index).Count(),
            game.RegionsOf(s.Index).Sum(r => r.Buildings), s.Gold, s.Mana, s.Units))]);
}

static string Pct(int count, int total) => (count / (double)total).ToString("0%", CultureInfo.InvariantCulture);

static int Median(IEnumerable<int> values)
{
    var sorted = values.Order().ToList();
    return sorted[sorted.Count / 2];
}

int Arg(string name, int fallback) => ArgText(name) is { } text ? int.Parse(text, CultureInfo.InvariantCulture) : fallback;

string? ArgText(string name) => Array.IndexOf(args, name) is var i and >= 0 && i + 1 < args.Length ? args[i + 1] : null;

namespace Spellbound.SkirmishSim
{
    internal sealed record SeatResult(string Bot, int Points, int Regions, int Buildings, int Gold, int Mana, int Units);

    internal sealed record GameResult(
        string Winner, int WinnerSeat, string LeaderAfter6, int Margin, int WinnerCardPoints, int Contests, int Rounds, bool EndedEarly,
        IReadOnlyList<SeatResult> Seats);

    /// <summary>A strategy: picks a seat's orders for the next round, as a player would, using only what players see.</summary>
    internal abstract class Bot
    {
        public abstract string Name { get; }

        public abstract string Strategy { get; }

        public abstract List<SkirmishOrder> Orders(SkirmishGame game, int seat, Random random);

        /// <summary>Adds the order if the batch still passes the game's own check.</summary>
        protected static bool TryAdd(SkirmishGame game, int seat, List<SkirmishOrder> orders, SkirmishOrder order)
        {
            orders.Add(order);
            if (game.CheckOrders(seat, orders) is null)
            {
                return true;
            }

            orders.RemoveAt(orders.Count - 1);
            return false;
        }

        /// <summary>Free regions next to the seat's, richest terrain first, ties at random.</summary>
        protected static List<SkirmishRegion> Targets(SkirmishGame game, int seat, Random random) =>
            [.. game.Claimable(seat).OrderByDescending(r => r.Terrain is SkirmishTerrain.T3 or SkirmishTerrain.T4).ThenBy(_ => random.Next())];

        /// <summary>The seat's regions with room to build, including ones claimed in this batch, emptiest first.</summary>
        protected static IEnumerable<int> RoomToBuild(SkirmishGame game, int seat, List<SkirmishOrder> orders) =>
            game.RegionsOf(seat).Select(r => r.Id)
                .Concat(orders.OfType<ClaimOrder>().Select(c => c.RegionId))
                .OrderBy(id => game.Board[id].Buildings);

        protected static void FillWithBuilds(SkirmishGame game, int seat, List<SkirmishOrder> orders, BuildingType type)
        {
            foreach (var region in RoomToBuild(game, seat, orders).ToList())
            {
                for (var count = game.Rules.BuildingsPerOrder; count >= 1; count--)
                {
                    if (TryAdd(game, seat, orders, new BuildOrder(region, type, count)))
                    {
                        break;
                    }
                }
            }
        }
    }

    /// <summary>Claims everything it can reach, then builds towns.</summary>
    internal sealed class Expander : Bot
    {
        public override string Name => "Expander";

        public override string Strategy => "claims every region it can reach (richest terrain first), then builds towns";

        public override List<SkirmishOrder> Orders(SkirmishGame game, int seat, Random random)
        {
            var orders = new List<SkirmishOrder>();
            foreach (var region in Targets(game, seat, random))
            {
                TryAdd(game, seat, orders, new ClaimOrder(region.Id));
            }

            FillWithBuilds(game, seat, orders, BuildingType.Town);
            return orders;
        }
    }

    /// <summary>One claim a round; the rest goes into buildings.</summary>
    internal sealed class Builder : Bot
    {
        public override string Name => "Builder";

        public override string Strategy => "one claim a round, then fills its regions with towns (and a node every few rounds)";

        public override List<SkirmishOrder> Orders(SkirmishGame game, int seat, Random random)
        {
            var orders = new List<SkirmishOrder>();
            if (Targets(game, seat, random).FirstOrDefault() is { } region)
            {
                TryAdd(game, seat, orders, new ClaimOrder(region.Id));
            }

            FillWithBuilds(game, seat, orders, game.Round % 3 == 2 ? BuildingType.Node : BuildingType.Town);
            return orders;
        }
    }

    /// <summary>Recruits an army so it wins contests, and claims where others are likely to claim too.</summary>
    internal sealed class Fighter : Bot
    {
        public override string Name => "Fighter";

        public override string Strategy => "recruits Unit 3 every round to win contested claims, then claims two regions";

        public override List<SkirmishOrder> Orders(SkirmishGame game, int seat, Random random)
        {
            var orders = new List<SkirmishOrder>();
            for (var count = game.Rules.UnitsPerOrder; count >= 1 && !TryAdd(game, seat, orders, new RecruitOrder("unit-3", count)); count -= 5)
            {
            }

            // Regions next to someone else first: those are the ones that get contested.
            foreach (var region in Targets(game, seat, random)
                         .OrderByDescending(r => r.Neighbours.Any(n => game.Board[n].Owner is { } o && o != seat)))
            {
                TryAdd(game, seat, orders, new ClaimOrder(region.Id));
            }

            FillWithBuilds(game, seat, orders, BuildingType.Town);
            return orders;
        }
    }

    /// <summary>Plays like the Expander, but only every other round: a player who checks in half as often.</summary>
    internal sealed class HalfPresent : Bot
    {
        private readonly Expander expander = new();

        public override string Name => "Half-present";

        public override string Strategy => "plays like the Expander, but misses every other round";

        public override List<SkirmishOrder> Orders(SkirmishGame game, int seat, Random random) =>
            game.Round % 2 == 0 ? expander.Orders(game, seat, random) : [];
    }
}
