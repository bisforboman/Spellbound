// Skirmish simulation: bots with different strategies play many seeded 4-seat games on the real rules
// (Spellbound.Domain.Skirmish), and the results go to a markdown report. It measures what the design promises: more than
// one way to win, games that stay open (an early leader doesn't always win), and luck that matters without deciding
// everything. Deterministic: the same seed gives the same report. See docs/skirmish-design.md.
//
//   dotnet run --project tools/Spellbound.SkirmishSim -- [--games 1000] [--seed 7] [--out docs/skirmish-sim-results.md]
using System.Globalization;
using System.Text;
using Spellbound.Domain;
using Spellbound.Domain.Skirmish;
using Spellbound.SkirmishSim;

var games = Arg("--games", 1000);
var seed = Arg("--seed", 7);
var output = ArgText("--out") ?? "docs/skirmish-sim-results.md";
var rules = Overrides(SkirmishRules.Default, args);

var scenarios = new (string Title, Bot[] Bots)[]
{
    ("Four strategies", [new Expander(), new Builder(), new Fighter(), new Hexer()]),
    ("A player who quits after round 4", [new Expander(), new Fighter(), new Hexer(), new Quitter()]),
};

var text = new StringBuilder();
text.AppendLine("# Skirmish simulation results").AppendLine();
text.AppendLine("Generated by `tools/Spellbound.SkirmishSim` with the default `SkirmishRules`; don't edit by hand. "
                + $"Each scenario is {games} games of 4 seats, seeds {seed}–{seed + games - 1}, with the seats rotated every game "
                + "(so each bot plays every school and every start).").AppendLine();
if (args.Contains("--set"))
{
    text.AppendLine($"Rule changes tried: {string.Join(", ", args.Where((a, i) => i > 0 && args[i - 1] == "--set"))}.").AppendLine();
}

text.AppendLine("## Bots").AppendLine();
foreach (var bot in scenarios.SelectMany(s => s.Bots).DistinctBy(b => b.Name))
{
    text.AppendLine($"- **{bot.Name}:** {bot.Strategy}");
}

foreach (var (title, bots) in scenarios)
{
    var results = new List<GameResult>();
    for (var g = 0; g < games; g++)
    {
        var seated = Enumerable.Range(0, bots.Length).Select(i => bots[(i + g) % bots.Length]).ToList();
        results.Add(Play(seated, rules, seed + g));
    }

    Report(text, title, bots, results, rules);
}

File.WriteAllText(output, text.ToString());
Console.WriteLine(text);
Console.WriteLine($"Wrote {output}");
return;

static void Report(StringBuilder text, string title, Bot[] bots, List<GameResult> results, SkirmishRules rules)
{
    var games = results.Count;
    text.AppendLine().AppendLine($"## {title}").AppendLine();
    text.AppendLine("| Bot | Win rate | Points | Regions | Buildings | Battles won | Gold left | Mana left |").AppendLine("|---|---|---|---|---|---|---|---|");
    foreach (var bot in bots)
    {
        var seats = results.SelectMany(r => r.Seats).Where(s => s.Bot == bot.Name).ToList();
        text.AppendLine($"| {bot.Name} | {Pct(results.Count(r => r.Winner == bot.Name), games)} | {seats.Average(s => s.Points):0.0} | "
                        + $"{seats.Average(s => s.Regions):0.0} | {seats.Average(s => s.Buildings):0.0} | {seats.Average(s => s.Battles):0.0} | "
                        + $"{seats.Average(s => s.Gold):N0} | {seats.Average(s => s.Mana):N0} |");
    }

    text.AppendLine();
    var reachedHalf = results.Where(r => r.LeaderAtHalf is not null).ToList();
    text.AppendLine($"- **The leader at half time (round {rules.Rounds / 2}) wins** {Pct(reachedHalf.Count(r => r.LeaderAtHalf == r.Winner), Math.Max(1, reachedHalf.Count))} "
                    + $"of the {reachedHalf.Count} games that got that far (lower means comebacks happen).");
    text.AppendLine($"- **Winning margin:** median {Median(results.Select(r => r.Margin))} points; {Pct(results.Count(r => r.Margin <= 3), games)} of games are won by 3 points or less.");
    text.AppendLine($"- **Luck decided it:** the winner's card points were more than their margin in {Pct(results.Count(r => r.WinnerCardPoints > r.Margin), games)} of games.");
    text.AppendLine($"- **Per game:** {results.Average(r => r.Contests):0.0} contested claims, {results.Average(r => r.Captures):0.0} regions taken "
                    + $"({results.Average(r => r.Battles - r.Captures):0.0} attacks held: the bots only attack when they're sure to win, so battle luck "
                    + $"rarely matters here), {results.Average(r => r.Hexes):0.0} hexes cast.");
    text.AppendLine($"- **Wiped out:** {results.Average(r => r.Wiped):0.00} seats a game end with no regions; "
                    + $"{Pct(results.Count(r => r.Wiped > 0), games)} of games have at least one.");
    text.AppendLine($"- **How games end:** {Pct(results.Count(r => r.EndedEarly), games)} early by holding {rules.BoardShareToWin:0%} of the board; "
                    + $"the rest after {rules.Rounds} rounds (average {results.Average(r => r.Rounds):0.0}).");
    text.AppendLine($"- **Seat:** seat 1 wins {Pct(results.Count(r => r.WinnerSeat == 0), games)}, seat 2 {Pct(results.Count(r => r.WinnerSeat == 1), games)}, "
                    + $"seat 3 {Pct(results.Count(r => r.WinnerSeat == 2), games)}, seat 4 {Pct(results.Count(r => r.WinnerSeat == 3), games)}.");
}

static GameResult Play(List<Bot> seated, SkirmishRules rules, int seed)
{
    var game = SkirmishGame.Start([.. seated.Select((b, i) => ($"{b.Name}-{i + 1}", (MagicSchool)((seed + i) % 5)))], rules, new SeededRandom(seed));
    var luck = new SeededRandom(seed * 31 + 1);
    var choices = new Random(seed * 17 + 3);
    string? leaderAtHalf = null;
    var (contests, battles, captures, hexes) = (0, 0, 0, 0);
    while (!game.Ended)
    {
        var playing = game.Seats.Where(s => !s.Out && seated[s.Index].Plays(game)).Select(s => s.Index).ToHashSet();
        var orders = playing.ToDictionary(s => s, s => (IReadOnlyList<SkirmishOrder>)seated[s].Orders(game, s, choices));
        var report = game.PlayRound(orders, luck, playing);
        contests += report.Public.Count(l => l.Contains(" was claimed by ", StringComparison.Ordinal));
        captures += report.Public.Count(l => l.Contains(" took ", StringComparison.Ordinal));
        battles += report.Public.Count(l => l.Contains(" took ", StringComparison.Ordinal) || l.Contains(" held ", StringComparison.Ordinal));
        hexes += report.BySeat.Sum(lines => lines.Count(l => l.StartsWith("You cast Hex", StringComparison.Ordinal)));
        if (game.Round == rules.Rounds / 2)
        {
            leaderAtHalf = seated[game.Standings()[0].Index].Name;
        }
    }

    var standings = game.Standings();
    var winner = standings[0].Index;
    return new GameResult(
        seated[winner].Name, winner, leaderAtHalf,
        game.Score(winner).Total - game.Score(standings[1].Index).Total, game.Score(winner).Cards,
        contests, battles, captures, hexes, game.Round, game.Round < rules.Rounds,
        [.. game.Seats.Select(s => new SeatResult(
            seated[s.Index].Name, game.Score(s.Index).Total, game.RegionsOf(s.Index).Count(),
            game.RegionsOf(s.Index).Sum(r => r.Buildings), s.BattlesWon, s.Gold, s.Mana))]);
}

// --set Name=Value (repeatable) tries a rule change without editing the code, e.g. --set RegionGuard=40.
static SkirmishRules Overrides(SkirmishRules rules, string[] args)
{
    for (var i = 0; i < args.Length - 1; i++)
    {
        if (args[i] != "--set")
        {
            continue;
        }

        var (name, value) = (args[i + 1].Split('=')[0], args[i + 1].Split('=')[1]);
        var property = typeof(SkirmishRules).GetProperty(name) ?? throw new ArgumentException($"No rule {name}.");
        rules = rules with { }; // a copy to set on
        property.SetValue(rules, Convert.ChangeType(value, property.PropertyType, CultureInfo.InvariantCulture));
    }

    return rules;
}

static string Pct(int count, int total) => (count / (double)total).ToString("0%", CultureInfo.InvariantCulture);

static int Median(IEnumerable<int> values)
{
    var sorted = values.Order().ToList();
    return sorted[sorted.Count / 2];
}

int Arg(string name, int fallback) => ArgText(name) is { } value ? int.Parse(value, CultureInfo.InvariantCulture) : fallback;

string? ArgText(string name) => Array.IndexOf(args, name) is var i and >= 0 && i + 1 < args.Length ? args[i + 1] : null;

namespace Spellbound.SkirmishSim
{
    internal sealed record SeatResult(string Bot, int Points, int Regions, int Buildings, int Battles, int Gold, int Mana);

    internal sealed record GameResult(
        string Winner, int WinnerSeat, string? LeaderAtHalf, int Margin, int WinnerCardPoints,
        int Contests, int Battles, int Captures, int Hexes, int Rounds, bool EndedEarly, IReadOnlyList<SeatResult> Seats)
    {
        public int Wiped => Seats.Count(s => s.Regions == 0);
    }

    /// <summary>A strategy: picks a seat's orders for the next round, as a player would, using only what players see.</summary>
    internal abstract class Bot
    {
        public abstract string Name { get; }

        public abstract string Strategy { get; }

        /// <summary>Whether the player shows up (readies up) this round.</summary>
        public virtual bool Plays(SkirmishGame game) => true;

        public abstract List<SkirmishOrder> Orders(SkirmishGame game, int seat, Random random);

        /// <summary>Adds the order if the batch still passes the game's own check.</summary>
        protected static bool TryAdd(SkirmishGame game, int seat, List<SkirmishOrder> orders, SkirmishOrder order)
        {
            orders.Add(order);
            if (game.CheckOrders(seat, orders) is null)
            {
                return true;
            }

            orders.RemoveAt(orders.Count - 1);
            return false;
        }

        /// <summary>Free regions next to the seat's, richest terrain first, ties at random.</summary>
        protected static List<SkirmishRegion> Targets(SkirmishGame game, int seat, Random random) =>
            [.. game.Claimable(seat).OrderByDescending(r => r.Terrain is SkirmishTerrain.T3 or SkirmishTerrain.T4).ThenBy(_ => random.Next())];

        /// <summary>Other mages' regions next to the seat's that its army beats even with bad luck, weakest first.</summary>
        protected static List<SkirmishRegion> SureWins(SkirmishGame game, int seat) =>
            [.. game.Board.Regions
                .Where(r => r.Owner is { } o && o != seat && r.Neighbours.Any(n => game.Board[n].Owner == seat))
                .Where(r => game.AttackStrength(seat, r.Owner!.Value) * 0.9 > game.RegionDefense(r.Id) * 1.1)
                .OrderBy(r => game.RegionDefense(r.Id))];

        /// <summary>The seat's regions with room to build, including ones claimed in this batch, emptiest first.</summary>
        protected static IEnumerable<int> RoomToBuild(SkirmishGame game, int seat, List<SkirmishOrder> orders) =>
            game.RegionsOf(seat).Select(r => r.Id)
                .Concat(orders.OfType<ClaimOrder>().Select(c => c.RegionId))
                .OrderBy(id => game.Board[id].Buildings);

        protected static void FillWithBuilds(SkirmishGame game, int seat, List<SkirmishOrder> orders, BuildingType type)
        {
            foreach (var region in RoomToBuild(game, seat, orders).ToList())
            {
                for (var count = game.Rules.BuildingsPerOrder; count >= 1; count--)
                {
                    if (TryAdd(game, seat, orders, new BuildOrder(region, type, count)))
                    {
                        break;
                    }
                }
            }
        }

        protected static void Recruit(SkirmishGame game, int seat, List<SkirmishOrder> orders, string unitId)
        {
            for (var count = game.Rules.UnitsPerOrder; count >= 1 && !TryAdd(game, seat, orders, new RecruitOrder(unitId, count)); count -= 5)
            {
            }
        }

        /// <summary>The seat's own school spell (not the ward).</summary>
        protected static string OwnSpell(SkirmishGame game, int seat) =>
            SpellBook.ForSchool(game.Seats[seat].School).First(s => s.School is not null).Id;
    }

    /// <summary>Claims everything it can reach, then builds towns; once the board is full it arms and attacks.</summary>
    internal sealed class Expander : Bot
    {
        public override string Name => "Expander";

        public override string Strategy => "claims every region it can reach (richest terrain first) and builds towns; when nothing is free, recruits and attacks sure wins";

        public override List<SkirmishOrder> Orders(SkirmishGame game, int seat, Random random)
        {
            var orders = new List<SkirmishOrder>();
            foreach (var region in Targets(game, seat, random))
            {
                TryAdd(game, seat, orders, new ClaimOrder(region.Id));
            }

            if (orders.Count == 0)
            {
                foreach (var region in SureWins(game, seat))
                {
                    TryAdd(game, seat, orders, new AttackOrder(region.Id));
                }

                Recruit(game, seat, orders, "unit-2");
            }

            FillWithBuilds(game, seat, orders, BuildingType.Town);
            return orders;
        }
    }

    /// <summary>One claim a round, its school's spell when it can, the rest into buildings and some defenders.</summary>
    internal sealed class Builder : Bot
    {
        public override string Name => "Builder";

        public override string Strategy => "one claim a round, its school's self-spell whenever none is running, then towns (a node every few rounds) and defenders";

        public override List<SkirmishOrder> Orders(SkirmishGame game, int seat, Random random)
        {
            var orders = new List<SkirmishOrder>();
            if (Targets(game, seat, random).FirstOrDefault() is { } region)
            {
                TryAdd(game, seat, orders, new ClaimOrder(region.Id));
            }

            if (game.Seats[seat].Effects.Count == 0)
            {
                TryAdd(game, seat, orders, new CastOrder(OwnSpell(game, seat)));
            }

            FillWithBuilds(game, seat, orders, game.Round % 3 == 2 ? BuildingType.Node : BuildingType.Town);
            Recruit(game, seat, orders, "unit-1");
            return orders;
        }
    }

    /// <summary>Builds an army and takes regions from others whenever it surely wins.</summary>
    internal sealed class Fighter : Bot
    {
        public override string Name => "Fighter";

        public override string Strategy => "recruits Unit 3 every round, attacks regions it surely wins, claims with what's left";

        public override List<SkirmishOrder> Orders(SkirmishGame game, int seat, Random random)
        {
            var orders = new List<SkirmishOrder>();
            foreach (var region in SureWins(game, seat))
            {
                TryAdd(game, seat, orders, new AttackOrder(region.Id));
            }

            Recruit(game, seat, orders, "unit-3");
            foreach (var region in Targets(game, seat, random))
            {
                TryAdd(game, seat, orders, new ClaimOrder(region.Id));
            }

            return orders;
        }
    }

    /// <summary>Hexes whoever leads, keeps a ward up, and claims.</summary>
    internal sealed class Hexer : Bot
    {
        public override string Name => "Hexer";

        public override string Strategy => "hexes the leader every round, keeps a ward up, claims and builds nodes";

        public override List<SkirmishOrder> Orders(SkirmishGame game, int seat, Random random)
        {
            var orders = new List<SkirmishOrder>();
            if (game.Standings().FirstOrDefault(s => s.Index != seat && !s.Out) is { } leader)
            {
                TryAdd(game, seat, orders, new HexOrder(SpellBook.HexesForSchool(game.Seats[seat].School).First().Id, leader.Index));
            }

            if (game.Seats[seat].Effects.All(e => e.SpellId != "ward"))
            {
                TryAdd(game, seat, orders, new CastOrder("ward"));
            }

            foreach (var region in Targets(game, seat, random))
            {
                TryAdd(game, seat, orders, new ClaimOrder(region.Id));
            }

            FillWithBuilds(game, seat, orders, BuildingType.Node);
            return orders;
        }
    }

    /// <summary>Plays like the Expander, then stops showing up after round 4.</summary>
    internal sealed class Quitter : Bot
    {
        private readonly Expander expander = new();

        public override string Name => "Quitter";

        public override string Strategy => "plays like the Expander for 4 rounds, then never readies up again";

        public override bool Plays(SkirmishGame game) => game.Round < 4;

        public override List<SkirmishOrder> Orders(SkirmishGame game, int seat, Random random) => expander.Orders(game, seat, random);
    }
}
