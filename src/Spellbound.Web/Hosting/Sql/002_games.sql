-- Many games instead of one round: a server can run several games at once (each Realm round is one, and Skirmishes
-- will be more). The game names its modes and writes its rules; the host only keeps the clock.
-- Never edit a released script; add a higher-numbered one.

CREATE TABLE games (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mode text NOT NULL,                   -- the game's name for the kind of game, e.g. its always-on one
    number int NOT NULL,                  -- counts up per mode: round 1, round 2, ...
    starts_at timestamptz NOT NULL,
    ends_at timestamptz NOT NULL,
    ended_at timestamptz,                 -- set when its end has been wrapped up (in the same transaction); null while running
    rules jsonb NOT NULL,                 -- the game's rules for this game, as the game wrote them; the host never reads them
    created_at timestamptz NOT NULL,
    UNIQUE (mode, number)
);
CREATE INDEX games_running ON games (mode) WHERE ended_at IS NULL;

-- The round being played becomes a running game, keeping its number as its id so the game's tables can follow it.
-- Its mode is left empty for the game's own script to name.
INSERT INTO games (id, mode, number, starts_at, ends_at, rules, created_at)
SELECT number, '', number, starts_at, ends_at, '{}', starts_at FROM current_round;

DROP TABLE current_round;
